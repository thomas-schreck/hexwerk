#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md for the statically linked components.

Usage: scripts/third-party-notices.py <yara-x source checkout> [output]

The YARA-X checkout must match the linked library version (e.g.
`git clone --depth 1 --branch v1.23.0 https://github.com/VirusTotal/yara-x`).
`cargo metadata` resolves the crates of `capi/` for aarch64-apple-darwin and
downloads their sources into ~/.cargo/registry; no crate code is executed.
License texts are taken from each crate's own LICENSE/COPYING/NOTICE files
and grouped when identical.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)([-._].*)?$", re.I)

LIBYAML = """Copyright (c) 2017-2020 Ingy döt Net
Copyright (c) 2006-2016 Kirill Simonov

Permission is hereby granted, free of charge, to any person obtaining a copy of
this software and associated documentation files (the "Software"), to deal in
the Software without restriction, including without limitation the rights to
use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies
of the Software, and to permit persons to whom the Software is furnished to do
so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE."""


def brew_prefix(formula):
    return pathlib.Path(subprocess.check_output(["brew", "--prefix", formula], text=True).strip())


def crates(yara_x):
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", "aarch64-apple-darwin",
         "--manifest-path", str(yara_x / "capi" / "Cargo.toml")],
        text=True, stderr=subprocess.DEVNULL))
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "yara-x-capi")
    seen, todo = set(), [root]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for dep in nodes[i]["deps"]:
            if any(k["kind"] in (None, "normal") for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return sorted((pkgs[i] for i in seen), key=lambda p: (p["name"], p["version"]))


def crate_texts(pkg, yara_x):
    d = pathlib.Path(pkg["manifest_path"]).parent
    files = sorted(f for f in d.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    if not files and str(d).startswith(str(yara_x)):
        files = [yara_x / "LICENSE"]   # workspace crates share the top-level license
    return [f.read_text(errors="replace").strip() for f in files]


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    yara_x = pathlib.Path(sys.argv[1]).resolve()
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "THIRD_PARTY_NOTICES.md"
    version = re.search(r'^version = "(.+)"', (yara_x / "Cargo.toml").read_text(), re.M).group(1)

    parts = ["""# Third-party notices

hexwerk itself is released under the MIT License (see `LICENSE`). The hexwerk
app and command line tool contain the components listed below. Their licenses
require these notices to accompany binary distributions; `make app` copies this
file into the app bundle.

This file is generated by `scripts/third-party-notices.py`; do not edit it by
hand.

Components linked dynamically from macOS itself (zlib, bzip2, liblzma,
libiconv, JavaScriptCore, CryptoKit, CommonCrypto) are not distributed with
hexwerk and are not listed.

The Kaitai Struct format collection is not part of hexwerk; `make formats`
downloads it, and each format keeps its own license (see the `meta/license`
field of each `.ksy` file). For the copies used as test fixtures see
`Tests/HexwerkCoreTests/Fixtures/ksy/README.md`.

The MD2 and MD4 implementations are hexwerk's own code; only the algorithm
constants are taken from RFC 1319 and RFC 1320.
"""]

    def section(title, note, text):
        parts.append(f"## {title}\n\n{note}\n\n```text\n{text.strip()}\n```\n")

    section(f"YARA-X {version}", "BSD-3-Clause. Statically linked (`libyara_x_capi.a`).",
            (yara_x / "LICENSE").read_text())
    magic = brew_prefix("libmagic")
    section("libmagic (file)", "BSD-2-Clause. Statically linked; the compiled database `magic.mgc` is bundled in the app.",
            (magic / "COPYING").read_text())
    co = ROOT / ".build" / "checkouts"
    section("Yams", "MIT. Swift package.", (co / "Yams" / "LICENSE").read_text())
    section("libyaml (bundled in Yams)", "MIT.", LIBYAML)
    section("Swift Argument Parser", "Apache-2.0 (with Runtime Library Exception). Swift package, command line tool only.",
            (co / "swift-argument-parser" / "LICENSE.txt").read_text())

    # Rust crates inside libyara_x_capi.a, grouped by identical license text.
    groups, missing = {}, []
    pkgs = crates(yara_x)
    for p in pkgs:
        texts = crate_texts(p, yara_x)
        if not texts:
            missing.append(p)
            continue
        for t in texts:
            key = hashlib.sha256(t.encode()).hexdigest()
            groups.setdefault(key, (t, []))[1].append(f'{p["name"]} {p["version"]}')
    parts.append(f"## Rust crates in YARA-X\n\nYARA-X {version} statically links {len(pkgs)} Rust crates "
                 "(dependencies of `yara-x-capi` for aarch64-apple-darwin). All are under permissive licenses:\n\n"
                 "| Crate | Version | License |\n|---|---|---|\n" +
                 "".join(f'| {p["name"]} | {p["version"]} | {p["license"] or "see below"} |\n' for p in pkgs))
    if missing:
        parts.append("The following crates ship no license file; their SPDX license applies with the standard text "
                     "of that license as reproduced elsewhere in this file:\n\n" +
                     "".join(f'- {p["name"]} {p["version"]} ({p["license"]}), copyright: '
                         f'{", ".join(p.get("authors") or []) or "the crate authors"}\n' for p in missing))
    for i, (text, names) in enumerate(sorted(groups.values(), key=lambda g: (-len(g[1]), g[1][0])), 1):
        section(f"Crate license text {i}", "Applies to: " + ", ".join(names) + ".", text)

    out.write_text("\n".join(parts))
    print(f"{out}: {len(pkgs)} crates, {len(groups)} distinct license texts, {len(missing)} without license file")


if __name__ == "__main__":
    main()
